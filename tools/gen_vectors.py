"""Generate known-answer vectors for USNA Secure vault format v1.
Independent of the Rust code: uses OpenSSL-backed Argon2id/HKDF/ChaCha20-Poly1305 from the
`cryptography` package. Run:  python3 tools/gen_vectors.py   (prints Rust constants)
The format constants here MUST mirror docs/VAULT_FORMAT.md."""
import hashlib, json, struct
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.argon2 import Argon2id
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from xchacha_ref import xchacha_encrypt

MAGIC_HDR = b"USNAVLT\x00"; MAGIC_DB = b"USNADB\x00\x00"
VERSION = 1
L_KEK = b"USNA Secure v1/kek"
L_SUB = {"database": b"USNA Secure v1/subkey/database",
         "filekey_wrap": b"USNA Secure v1/subkey/filekey-wrap",
         "manifest": b"USNA Secure v1/subkey/manifest"}
A_VK = b"USNA Secure v1/vk-wrap"; A_DB = b"USNA Secure v1/snapshot"; A_FK = b"USNA Secure v1/filekey"

def hkdf(ikm, salt, info): return HKDF(hashes.SHA256(), 32, salt, info).derive(ikm)

# ---- inputs -------------------------------------------------------------------------
password = b"correct horse battery staple"
salt = bytes(range(0x00, 0x20)); vault_id = bytes(range(0xa0, 0xb0))
gen = 1; m, t, p = 8, 1, 1
vk = bytes(range(0x40, 0x60)); wrap_nonce = bytes(range(0x80, 0x98))

# ---- header ---------------------------------------------------------------------------
pdk = Argon2id(salt=salt, length=32, iterations=t, lanes=p, memory_cost=m).derive(password)
kek = hkdf(pdk, vault_id, L_KEK)
prefix = (MAGIC_HDR + struct.pack("<HH", VERSION, 0) + vault_id + struct.pack("<I", gen)
          + b"\x01" + struct.pack("<III", m, t, p) + salt)
assert len(prefix) == 77
wrapped_vk = xchacha_encrypt(kek, wrap_nonce, A_VK + prefix, vk)
assert len(wrapped_vk) == 48
header = prefix + wrap_nonce + wrapped_vk
assert len(header) == 149

# ---- subkeys --------------------------------------------------------------------------
subs = {k: hkdf(vk, vault_id, lab + struct.pack("<I", gen)) for k, lab in L_SUB.items()}

# ---- snapshot -------------------------------------------------------------------------
revision = 7; snap_pt = b"USNA Secure snapshot vector"; snap_nonce = bytes(range(0xc0, 0xd8))
inner = struct.pack("<Q", len(snap_pt)) + snap_pt
inner += b"\x00" * ((-len(inner)) % 4096)
snap_prefix = MAGIC_DB + struct.pack("<HH", VERSION, 0) + vault_id + struct.pack("<I", gen) + struct.pack("<Q", revision)
assert len(snap_prefix) == 40
snap_ct = xchacha_encrypt(subs["database"], snap_nonce, A_DB + snap_prefix, inner)
snapshot = snap_prefix + snap_nonce + snap_ct
assert len(snapshot) == 40 + 24 + 4096 + 16

# ---- wrapped file key -----------------------------------------------------------------
file_key = bytes(range(0x10, 0x30)); object_id = bytes(range(0xe0, 0xf0)); fk_nonce = bytes(range(0x00, 0x18))
fk_ct = xchacha_encrypt(subs["filekey_wrap"], fk_nonce, A_FK + vault_id + struct.pack("<I", gen) + object_id, file_key)
wrapped_fk = fk_nonce + fk_ct
assert len(wrapped_fk) == 72

def rs(name, b): print(f'pub const {name}: &str = "{b.hex()}";')
print("// ---- generated by tools/gen_vectors.py ----")
rs("KAT_PDK", pdk); rs("KAT_KEK", kek)
rs("KAT_HEADER", header)
for k, v in subs.items(): rs("KAT_SUBKEY_" + k.upper(), v)
print(f"pub const KAT_SNAPSHOT_LEN: usize = {len(snapshot)};")
rs("KAT_SNAPSHOT_PREFIX", snap_prefix + snap_nonce)
rs("KAT_SNAPSHOT_SHA256", hashlib.sha256(snapshot).digest())
rs("KAT_WRAPPED_FILEKEY", wrapped_fk)

# ---- emit files ------------------------------------------------------------------------
import os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "vault-core")
vec_dir = os.path.join(root, "tests", "vectors"); os.makedirs(vec_dir, exist_ok=True)
for name, data in [("header_v1.bin", header), ("snapshot_v1.bin", snapshot), ("wrapped_filekey_v1.bin", wrapped_fk)]:
    with open(os.path.join(vec_dir, name), "wb") as f: f.write(data)
with open(os.path.join(vec_dir, "vectors_v1.json"), "w") as f:
    json.dump({"password_utf8": password.decode(), "argon2id": {"m_kib": m, "t": t, "p": p}, "salt": salt.hex(),
               "vault_id": vault_id.hex(), "vk_generation": gen, "vk": vk.hex(), "wrap_nonce": wrap_nonce.hex(),
               "snapshot": {"revision": revision, "plaintext_utf8": snap_pt.decode(), "nonce": snap_nonce.hex()},
               "file_key": file_key.hex(), "object_id": object_id.hex(), "filekey_wrap_nonce": fk_nonce.hex()}, f, indent=2)
lines = ["//! GENERATED by tools/gen_vectors.py from an independent implementation. Do not edit by hand.\n",
         "// `dead_code` is allowed because this generated file lists every vector while each unit test\n",
         "// uses only some of them.\n", "#![allow(dead_code)]\n"]
def c(name, b): lines.append(f'pub const {name}: &str = "{b.hex()}";\n')
c("PDK", pdk); c("KEK", kek); c("HEADER", header)
for k, v in subs.items(): c("SUBKEY_" + k.upper(), v)
lines.append(f"pub const SNAPSHOT_LEN: usize = {len(snapshot)};\n")
c("SNAPSHOT_SHA256", hashlib.sha256(snapshot).digest()); c("WRAPPED_FILEKEY", wrapped_fk)
c("VK", vk); c("SALT", salt); c("VAULT_ID", vault_id); c("WRAP_NONCE", wrap_nonce)
c("SNAPSHOT_NONCE", snap_nonce); c("FILE_KEY", file_key); c("OBJECT_ID", object_id); c("FILEKEY_WRAP_NONCE", fk_nonce)
lines.append('pub const PASSWORD: &str = "correct horse battery staple";\n')
lines.append(f"pub const SNAPSHOT_REVISION: u64 = {revision};\n")
lines.append(f'pub const SNAPSHOT_PLAINTEXT: &[u8] = b"{snap_pt.decode()}";\n')
with open(os.path.join(root, "src", "test_vectors.rs"), "w") as f: f.writelines(lines)
print("wrote golden files + test_vectors.rs", file=sys.stderr)
